#!/usr/bin/env python3
"""Writes the constant strings of a C++ framework, recovered from the static
initializers of its x86_64 build, as C++: the LConstantStrings and the
LString pointers to them, global or static class members.

usage: gen_strings.py <appmodel|renderlib> <out.cpp> <out.h>
"""
import re
import struct
import subprocess
import sys

sys.path.insert(0, 'tools')
from dis64 import load, sections, strings  # noqa: E402

name, out_cpp, out_h = sys.argv[1:4]
path, lines = load(name)
texts = strings(path, lines)

data = open(path, 'rb').read()
secs = sections(path)
addrs, syms = {}, {}
for line in subprocess.run(['nm', path], capture_output=True, text=True).stdout.splitlines():
    p = line.split(None, 2)
    if len(p) == 3:
        addrs[p[2]] = int(p[0], 16)
        syms.setdefault(int(p[0], 16), p[2])


def target(sym):
    a = addrs[sym]
    for s in secs:
        if s['name'] in ('__data', '__const') and s['addr'] <= a < s['addr'] + s['size']:
            o = s['offset'] + a - s['addr']
            return syms.get(struct.unpack('<Q', data[o:o + 8])[0])


names = sorted(texts)
dem = dict(zip(names, subprocess.run(['c++filt'], input='\n'.join(names), capture_output=True,
                                     text=True).stdout.splitlines()))


def cname(sym):
    d = dem[sym]
    if d == sym:
        return sym[1:]  # strip the Mach-O underscore
    return d


consts = [s for s in names if not texts[s].startswith('-> ')]
ptrs = [s for s in names if texts[s].startswith('-> ')]
umbrella = {'renderlib': 'RenderLib.h'}.get(name, 'AppModel.h')
cpp = ['// Constant strings, generated by tools/gen_strings.py from the static',
       '// initializers of the original binary.', '', '#include "%s"' % umbrella, '']
hdr = ['// Constant strings, generated by tools/gen_strings.py.', '', '#ifndef %s_STRINGS_H' % name.upper(),
       '#define %s_STRINGS_H' % name.upper(), '', '#include "LString.h"', '', 'using namespace LF;', '']


def lit(t):
    return '"' + t.replace('"', '\\"') + '"'


for s in consts:
    c = cname(s)
    if '::' in c:
        cpp.append('LConstantString %s(%s);' % (c, lit(texts[s])))
    else:
        cpp.append('LConstantString %s(%s);' % (c, lit(texts[s])))
        hdr.append('extern LConstantString %s;' % c)
cpp.append('')
hdr.append('')
for s in ptrs:
    c = cname(s)
    t = target(s)
    tc = cname(t) if t in dem else None
    # The ...Remap tables are arrays of pointers, written by hand.
    if tc is None or c.endswith('Remap'):
        continue
    cpp.append('LString *%s = &%s;' % (c, tc))
    if '::' not in c:
        hdr.append('extern LString *%s;' % c)
hdr += ['', '#endif', '']
open(out_cpp, 'w').write('\n'.join(cpp) + '\n')
open(out_h, 'w').write('\n'.join(hdr) + '\n')
print(len(consts), 'strings', len(ptrs), 'pointers')
