#!/usr/bin/env python3
"""Writes translation worksheets for a C++ framework: one file per class
under <outdir>/, holding every function of that class as an UNTRANSLATED
block with Ghidra's decompilation, plus a header comment with what the binary
says about the class (i386 size, bases, vtable order, field offsets used).
Free functions go to the worksheet of the class whose code precedes them
(the same compilation unit). Functions the class macros and the compiler
generate (_classImp_, TClassPool, thunks, static initialisers) are listed in
<outdir>/_generated.txt instead of getting worksheets.

Never overwrites an existing worksheet.

usage: gen_worksheets.py <binary-name> <outdir>     e.g. lfoundation src/LFoundation
"""
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), '..')

GENERATED = re.compile(r'_classImp_|TClassPool<|_TAllocator<|_allocatorClass|'
                       r'^(non-virtual|virtual) thunk|^__static_initialization|^_GLOBAL_|'
                       r'__GLOBAL__|^__tcf_|typeinfo|^guard variable')


def outer_class(owner):
    """'LF::LClass::LOutletInstaller' -> 'LClass'; templates -> template name"""
    if owner is None:
        return None
    parts = []
    depth = 0
    cur = ''
    for ch in owner:
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        if ch == ':' and depth == 0:
            if cur:
                parts.append(cur)
            cur = ''
            continue
        cur += ch
    parts.append(cur)
    names = [p for p in parts if p not in ('LF', 'std')]
    if not names:
        return None
    return re.sub(r'<.*', '', names[0])


def file_name(cls):
    return re.sub(r'[^A-Za-z0-9_]', '_', cls)


def main():
    name, outdir = sys.argv[1:3]
    analysis = os.path.join(ROOT, 'analysis')
    cxx = json.load(open(os.path.join(analysis, 'cxx-%s.json' % name)))
    decomp = os.path.join(analysis, 'decomp', '%s-i386' % name)
    index = [l.rstrip('\n').split('\t') for l in open(os.path.join(decomp, 'index.tsv'))]

    classes = {c['name']: c for c in cxx}
    objc_classes = set()
    objc_path = os.path.join(analysis, 'objc-%s.json' % name)
    if os.path.exists(objc_path):
        for mod in json.load(open(objc_path)):
            objc_classes.update(c['name'] for c in mod['classes'])
            objc_classes.update(c['class'] for c in mod.get('categories', []) if c.get('class'))
    owner_of = {}       # address -> class name, from the symbol table
    for c in cxx:
        for m in c['methods']:
            owner_of[int(m['addr'], 16)] = (c['name'], m['decl'])

    # i386 sizes, from operator_new(size) in each class's _alloc
    sizes = {}
    for addr, size, fname, file in index:
        m = re.match(r'(.*)::_classImp_::_alloc$', fname)
        if m:
            text = open(os.path.join(decomp, file), errors='replace').read()
            s = re.search(r'operator_new\((0x[0-9a-f]+|\d+)', text)
            if s:
                sizes[m.group(1)] = int(s.group(1), 0)

    os.makedirs(outdir, exist_ok=True)
    sheets = {}         # worksheet name -> list of (addr, decl, owner, file)
    generated = []
    last = None
    for addr, size, fname, file in sorted(index, key=lambda r: int(r[0], 16)):
        a = int(addr, 16)
        owner, decl = owner_of.get(a, (None, fname))
        if GENERATED.search(fname) or GENERATED.search(decl) or (owner and GENERATED.search(owner)):
            generated.append('%s\t%s' % (addr, decl))
            continue
        if fname.startswith(('-[', '+[')):
            body = fname[2:]
            sheet = max((c for c in objc_classes if body.startswith(c + '_')), key=len,
                        default=body.split('_')[0])
        else:
            sheet = outer_class(owner) if owner else None
            if sheet is None:
                sheet = last or '_free'
        last = sheet
        sheets.setdefault(sheet, []).append((addr, decl, owner, file))

    for sheet, funcs in sorted(sheets.items()):
        path = os.path.join(outdir, file_name(sheet) + ('.mm' if any(
            f[1].startswith(('-[', '+[')) for f in funcs) else '.cpp'))
        if os.path.exists(path):
            continue
        out = []
        out.append('// %s' % sheet)
        out.append('// Worksheet generated by tools/gen_worksheets.py from analysis/decomp/%s-i386.'
                   % name)
        out.append('// Translating a function means replacing its UNTRANSLATED block with code.')
        for cname in sorted({f[2] for f in funcs if f[2]} | {
                c for c in classes if outer_class(c) == sheet and classes[c]['vtable']}):
            c = classes.get(cname)
            if not c:
                continue
            out.append('//')
            info = cname
            if cname in sizes:
                info += ', i386 size 0x%x' % sizes[cname]
            if c['bases']:
                info += ', bases: ' + ', '.join(
                    '%s%s' % (b['name'], ' @0x%x' % b['offset'] if b.get('offset') else '')
                    for b in c['bases'])
            out.append('// ' + info)
            if c['vtable']:
                out.append('//   vtable:')
                for i, v in enumerate(c['vtable']):
                    out.append('//   %4d +0x%02x %s' % (i, 4 * i, v))
            fields = field_offsets(decomp, [f for f in funcs if f[2] == cname])
            if fields:
                out.append('//   this+offset used: ' + ', '.join(
                    '0x%x %s' % (o, '/'.join(sorted(t))) for o, t in sorted(fields.items())))
        out.append('')
        for addr, decl, owner, file in funcs:
            text = open(os.path.join(decomp, file), errors='replace').read()
            text = annotate_vcalls(text, classes.get(owner))
            body = '\n'.join(l for l in text.split('\n')[1:] if l.strip() != '')
            out.append('/* UNTRANSLATED %s @%s' % (decl, addr))
            out.append(body.replace('*/', '* /'))
            out.append('*/')
            out.append('')
        open(path, 'w').write('\n'.join(out))

    count = os.path.join(outdir, '_count.txt')
    if not os.path.exists(count):
        open(count, 'w').write('%d\n' % sum(len(f) for f in sheets.values()))
    open(os.path.join(outdir, '_generated.txt'), 'w').write(
        '# functions the class macros, templates and the compiler generate\n' +
        '\n'.join(generated) + '\n')
    print('%s: %d worksheets, %d functions, %d generated' % (
        name, len(sheets), sum(len(f) for f in sheets.values()), len(generated)))


ACCESS = re.compile(r'\*\((\w+(?: \*)*) \*\)\(this \+ (0x[0-9a-f]+|\d+)\)|this\[(0x[0-9a-f]+|\d+)\]')


def field_offsets(decomp, funcs):
    fields = {}
    for addr, decl, owner, file in funcs:
        text = open(os.path.join(decomp, file), errors='replace').read()
        for m in ACCESS.finditer(text):
            if m.group(2):
                fields.setdefault(int(m.group(2), 0), set()).add(m.group(1))
            else:
                fields.setdefault(int(m.group(3), 0), set()).add('byte')
    return fields


VCALL = re.compile(r'\(\*\*\(code \*\*\)\(\*\(int \*\)this \+ (0x[0-9a-f]+|\d+)\)\)')


def annotate_vcalls(text, cls):
    if not cls or not cls['vtable']:
        return text
    vt = cls['vtable']

    def sub(m):
        i = int(m.group(1), 0) // 4
        name = vt[i] if i < len(vt) and vt[i] else '?'
        return m.group(0) + ' /* %s */' % name.split('(')[0]
    return VCALL.sub(sub, text)


if __name__ == '__main__':
    main()
